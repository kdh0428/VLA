#!/usr/bin/env python
"""review_followup4 A5: record the regeneration check run from the unzipped ZIP copy (2026-10-18). CPU only.

Reads <unzipped>/REGEN_RESULTS.csv (written by regen_compare.py inside the unzipped ZIP) and writes
outputs/review_followup4/REPRO_CHECK.csv and REPRO_CHECK.md. Also compares each regenerated file's sha256 with the
live repository original (which was never touched).

  nice -n 19 /root/miniforge3/envs/autovla/bin/python c_repro_record.py <unzipped dir>
"""
import hashlib
import json
import os
import sys
import zipfile

import pandas as pd

POC = "/root/VLA/autovla_misalignment_poc"
R4 = f"{POC}/outputs/review_followup4"
ZIP = f"{R4}/reproducibility_minimal.zip"


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def main():
    d = sys.argv[1]
    r = pd.read_csv(f"{d}/REGEN_RESULTS.csv")
    r["sha256_live_repo"] = [sha(f"{POC}/{f}") if os.path.exists(f"{POC}/{f}") else "" for f in r.file]
    r["regenerated_equals_live_repo_bytes"] = r.sha256_regenerated == r.sha256_live_repo
    r.to_csv(f"{R4}/REPRO_CHECK.csv", index=False)
    info = json.loads(zipfile.ZipFile(ZIP).read("BUILD_INFO.json"))
    zsize = os.path.getsize(ZIP)
    counts = r.verdict.value_counts().to_dict()
    lines = [
        "# REPRO_CHECK — regeneration of the core tables from reproducibility_minimal.zip (review_followup4 A5)",
        "",
        f"Date: 2026-10-18. ZIP: `outputs/review_followup4/reproducibility_minimal.zip`, {zsize / 1024 ** 2:.1f} MB "
        f"({info['n_files']} data/code files, {info['uncompressed_bytes'] / 1024 ** 2:.1f} MB uncompressed; built "
        f"{info['built_utc']}, git HEAD {info['git_head'][:7]}).",
        "",
        "**Procedure (actually run).** The ZIP was extracted with `python3 -m zipfile -e` into the scratchpad "
        "(`/tmp/claude-0/-root-VLA/3d5b895f-ebec-4409-a7c0-03065c2dc74b/scratchpad/repro_check`), `regen.sh` rewrote the "
        "`/root/VLA` prefix of the shipped code to the extracted folder, moved every target output aside and re-ran the "
        "producing script on the shipped inputs only (CPU, `nice -n 19`, single-threaded BLAS). The extracted copy was "
        "deleted afterwards. Comparison: exact bytes first; otherwise cell by cell (numeric rtol 1e-9, text exact; JSON "
        "timing/location keys ignored). The live repository files were never modified; the last column compares the "
        "regenerated bytes with them as well.",
        "",
        "**Summary:** " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f" (of {len(r)} files).",
        "",
        "| target | file | verdict | note | s | = live repo bytes |",
        "|---|---|---|---|---|---|",
    ]
    for _, x in r.iterrows():
        note = "" if pd.isna(x.note) else str(x.note)
        lines.append(f"| {x.target} | `{x.file}` | {x.verdict} | {note} | {x.seconds} | {'yes' if x.regenerated_equals_live_repo_bytes else 'no'} |")
    lines += ["", "What each target regenerates:", ""]
    for t, w in r.groupby("target").what.first().items():
        lines.append(f"- **{t}**: {w}")
    lines += ["", "Not in the regeneration set (inputs not shipped, see `MISSING.md` in the ZIP): the original P1-C decision "
              "analysis from mechanism raw (`analyze_p1c.py`; its frozen unit table is shipped and used by P0-A), A2's trace "
              "audit (needs the R8R9 exp9 raw), B1 analysis rows from the GPU run (`B/B1/run/` is shipped, so "
              "`b1_analyze.py` can be run, but it was not part of the scripted check), and any GPU run."]
    open(f"{R4}/REPRO_CHECK.md", "w").write("\n".join(lines) + "\n")
    json.dump({"zip_mb": round(zsize / 1024 ** 2, 1), "counts": counts, "n_files_compared": len(r),
               "n_identical_bytes": int((r.verdict == "IDENTICAL_BYTES").sum()),
               "n_match_values": int((r.verdict == "MATCH_VALUES").sum()),
               "n_mismatch_or_failed": int((~r.verdict.isin(["IDENTICAL_BYTES", "MATCH_VALUES"])).sum()),
               "targets": sorted(r.target.unique())}, open(f"{R4}/REPRO_CHECK_summary.json", "w"), indent=1)
    print(open(f"{R4}/REPRO_CHECK.md").read())


if __name__ == "__main__":
    main()
